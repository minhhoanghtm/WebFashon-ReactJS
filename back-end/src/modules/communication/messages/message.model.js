import mongoose from "mongoose";

const MessageSchema = new mongoose.Schema(
  {
    conversationId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "CommunicationConversation",
      required: true,
      index: true,
    },
    senderType: {
      type: String,
      enum: ["user", "admin", "ai", "system"],
      required: true,
      index: true,
    },
    senderId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: "User",
      default: null,
      index: true,
    },
    messageType: {
      type: String,
      enum: ["text", "image", "file", "product_card", "order_card", "system"],
      required: true,
      default: "text",
      index: true,
    },
    content: {
      type: String,
      required: true,
      trim: true,
    },
    // Generated by the client before a retry. Makes HTTP/socket retries idempotent.
    clientMessageId: {
      type: String,
      default: null,
      trim: true,
      maxlength: 128,
    },
    metadata: {
      type: mongoose.Schema.Types.Mixed,
      default: {},
    },
  },
  { timestamps: true }
);

MessageSchema.index({ conversationId: 1, createdAt: 1 });
MessageSchema.index(
  { senderId: 1, clientMessageId: 1 },
  { unique: true, partialFilterExpression: { clientMessageId: { $type: "string" } } },
);
MessageSchema.index({ conversationId: 1, senderType: 1, createdAt: -1 });
MessageSchema.index({ messageType: 1, createdAt: -1 });

const CommunicationMessage = mongoose.model("CommunicationMessage", MessageSchema);
export default CommunicationMessage;
